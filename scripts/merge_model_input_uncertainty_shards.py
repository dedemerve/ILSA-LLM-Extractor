#!/usr/bin/env python3
"""Validate and merge deterministic v4 model-input uncertainty draw shards."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
EXPECTED_RANGES = [(i, min(i + 250, 2000)) for i in range(0, 2000, 250)]
SCRIPT = ROOT / "scripts/run_pisa_model_input_uncertainty_v4.py"
EXPECTED_SCRIPT_HASH = "c51497ecfab0b1d52d3a59027670323ab4cee9631daf0525ceadb24f712ee13a"
METRIC_COLUMNS = {"draw", "target_cycle", "domain", "model", "fold_mae", "n_countries"}


def file_hash(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--shard-root", type=Path, default=ROOT / "outputs/reproducibility_check_v3/model_input_shards")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "outputs/reproducibility_check_v3/pisa_model_input_uncertainty_v4")
    args = parser.parse_args()
    shard_root, output = args.shard_root.resolve(), args.output_dir.resolve()
    if output.exists():
        raise FileExistsError(output)
    if file_hash(SCRIPT) != EXPECTED_SCRIPT_HASH:
        raise ValueError("v4 analysis source changed since the audited run")

    entries = []
    for start, stop in EXPECTED_RANGES:
        shard = shard_root / f"draws_{start:04d}_{stop:04d}"
        meta_path = shard / "shard_metadata.json"
        if not meta_path.is_file():
            raise FileNotFoundError(f"Missing completed shard metadata: {meta_path}")
        meta = json.loads(meta_path.read_text())
        if (meta["source_script_sha256"] != EXPECTED_SCRIPT_HASH or
                meta["draw_start_in_full_run"] != start or
                meta["draw_stop_in_full_run_exclusive"] != stop or
                meta["model_and_metric_code_unchanged"] is not True):
            raise ValueError(f"Shard metadata mismatch for {shard.name}")
        checkpoints = sorted((shard / "checkpoints").glob("draw_metrics_*.csv"))
        expected_starts = list(range(0, stop - start, 25))
        if len(checkpoints) != len(expected_starts):
            raise ValueError(f"Incomplete checkpoint set for {shard.name}: {len(checkpoints)} files")
        for checkpoint, local_start in zip(checkpoints, expected_starts):
            match = re.fullmatch(r"draw_metrics_(\d{4})_(\d{4})\.csv", checkpoint.name)
            if not match or int(match.group(1)) != local_start:
                raise ValueError(f"Unexpected checkpoint name/order: {checkpoint.name}")
            local_stop = min(local_start + 25, stop - start)
            frame = pd.read_csv(checkpoint)
            if set(frame.columns) != METRIC_COLUMNS:
                raise ValueError(f"Unexpected checkpoint schema: {checkpoint}")
            if set(frame["draw"].unique()) != set(range(local_start, local_stop)):
                raise ValueError(f"Incomplete local draw IDs: {checkpoint}")
            if len(frame) != (local_stop - local_start) * 60:
                raise ValueError(f"Unexpected checkpoint row count: {checkpoint}")
            frame["draw"] += start
            global_start, global_stop = start + local_start, start + local_stop
            entries.append((checkpoint, frame, global_start, global_stop))

    global_draws = {d for _, frame, _, _ in entries for d in frame["draw"].unique()}
    if global_draws != set(range(2000)):
        raise ValueError("Merged shards do not cover the exact global draw range 0..1999")
    output.mkdir(parents=True)
    check_dir = output / "checkpoints"
    check_dir.mkdir()
    manifest_rows = []
    for source, frame, start, stop in entries:
        dest = check_dir / f"draw_metrics_{start:04d}_{stop:04d}.csv"
        if dest.exists():
            raise FileExistsError(dest)
        frame.to_csv(dest, index=False)
        manifest_rows.append({"source": str(source), "source_sha256": file_hash(source),
                              "destination": dest.name, "destination_sha256": file_hash(dest),
                              "draw_start": start, "draw_stop_exclusive": stop,
                              "rows": len(frame)})
    merge_manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "analysis_script": str(SCRIPT), "analysis_script_sha256": EXPECTED_SCRIPT_HASH,
        "expected_global_draws": 2000, "draws_covered": len(global_draws),
        "seed_sequence": "Each shard used its exact slice from default_rng(20261015).integers(0,2**31,size=2000).",
        "merge_rows": manifest_rows,
        "note": "Checkpoint merge only; final summaries must be generated by the original v4 script in resume mode.",
    }
    (output / "shard_merge_manifest.json").write_text(json.dumps(merge_manifest, indent=2) + "\n")
    print(f"Merged {len(entries)} checkpoints covering {len(global_draws)} draws into {output}")


if __name__ == "__main__":
    main()
